"""Fifteen red tests for the sec-dep-pin exercise.

The first ten tests correspond to the ten defects in README.md, in order.
The remaining five are the independent acceptance checks requested for a
compliant lock, extras, a bad hash, a bad source and batch independence.

Do not edit this file. Make the tests pass by fixing src/deps/lock.py.
"""

import hashlib
import json

import pytest

from deps import lock


ALLOWED = "https://pypi.org/simple"
MIRROR = "https://pypi.org/simple-mirror"


def _entry(
    name="acme-utils",
    version="1.2.3",
    source=ALLOWED,
    data=b"acme-utils-wheel",
    algorithms=("sha256",),
):
    return {
        "name": name,
        "version": version,
        "source": source,
        "hashes": {
            algorithm: hashlib.new(algorithm, data).hexdigest()
            for algorithm in algorithms
        },
    }


def _policy():
    return {
        "allowed_sources": [ALLOWED],
        "verify_hashes": True,
        "require_transitive_pins": True,
    }


class _EqualityTrap(str):
    """A digest that rejects ordinary equality so constant-time checks show."""

    __hash__ = str.__hash__

    def __eq__(self, other):
        raise AssertionError("digest compared with ordinary equality")

    def __ne__(self, other):
        raise AssertionError("digest compared with ordinary inequality")


def test_parse_lock_preserves_source_and_hashes():
    packages = [
        {
            "name": "Acme_Utils",
            "version": "1.2.3",
            "source": ALLOWED,
            "hashes": {
                "sha256": "a" * 64,
                "sha512": "b" * 128,
            },
        }
    ]
    parsed = lock.parse_lock(json.dumps({"packages": packages}))
    assert parsed == packages


def test_normalize_name_equates_underscore_and_hyphen():
    assert lock.normalize_name("Acme_Utils") == "acme-utils"
    assert lock.normalize_name("ACME--Utils") == "acme-utils"
    assert lock.normalize_name("acme.utils") == "acme-utils"


def test_source_ok_rejects_mirror_prefix():
    entry = _entry(source=MIRROR)
    assert lock.source_ok(entry, [ALLOWED]) is False
    assert lock.source_ok(_entry(source=ALLOWED), [ALLOWED]) is True


def test_hash_ok_verifies_every_declared_algorithm():
    data = b"artifact-with-two-digests"
    entry = _entry(data=data, algorithms=("sha256", "sha512"))
    entry["hashes"]["sha512"] = "0" * 128
    assert lock.hash_ok(data, entry) is False


def test_hash_ok_uses_constant_time_comparison():
    data = b"constant-time-check"
    expected = _EqualityTrap(hashlib.sha256(data).hexdigest())
    entry = _entry(data=data)
    entry["hashes"]["sha256"] = expected
    assert lock.hash_ok(data, entry) is True


def test_resolve_reports_conflicting_exact_versions():
    entries = [
        _entry(version="1.0.0", data=b"version-one"),
        _entry(version="2.0.0", data=b"version-two"),
    ]
    constraints = [
        {"name": "acme-utils", "version": "1.0.0"},
        {"name": "Acme_Utils", "version": "2.0.0"},
    ]
    with pytest.raises(ValueError):
        lock.resolve(entries, constraints)


def test_diff_reports_extras_as_well_as_missing():
    expected = [_entry(name="acme-utils", data=b"expected")]
    actual = [_entry(name="shadow-helper", data=b"unexpected")]
    result = lock.diff(expected, actual)
    assert [entry["name"] for entry in result["missing"]] == ["acme-utils"]
    assert [entry["name"] for entry in result["extra"]] == ["shadow-helper"]


def test_diff_separates_changed_from_deleted():
    expected = [_entry(version="1.0.0", data=b"old")]
    actual = [_entry(version="2.0.0", data=b"new")]
    result = lock.diff(expected, actual)
    assert result["missing"] == []
    assert len(result["changed"]) == 1
    assert result["changed"][0]["expected"]["version"] == "1.0.0"
    assert result["changed"][0]["actual"]["version"] == "2.0.0"


def test_validate_policy_flags_unverified_hashes():
    policy = _policy()
    policy["verify_hashes"] = False
    assert lock.validate_policy(policy) == ["UNVERIFIED_HASHES"]

    unpinned = _policy()
    unpinned["require_transitive_pins"] = False
    assert lock.validate_policy(unpinned) == ["UNPINNED_TRANSITIVE"]


def test_lock_batch_isolates_manifests():
    policy = _policy()
    manifests = [
        {
            "id": "first",
            "entries": [_entry(version="1.0.0", data=b"first")],
            "constraints": [{"name": "acme-utils", "version": "1.0.0"}],
        },
        {
            "id": "second",
            "entries": [_entry(version="2.0.0", data=b"second")],
            "constraints": [{"name": "acme-utils", "version": "2.0.0"}],
        },
    ]
    result = lock.lock_batch(manifests, policy)
    assert result["first"]["resolved"]["acme-utils"]["version"] == "1.0.0"
    assert result["second"]["resolved"]["acme-utils"]["version"] == "2.0.0"


def test_compliant_manifest_passes_all_checks():
    data = b"compliant-wheel"
    entry = _entry(data=data, algorithms=("sha256", "sha512"))
    parsed = lock.parse_lock(json.dumps({"packages": [entry]}))

    assert lock.normalize_name(parsed[0]["name"]) == "acme-utils"
    assert lock.source_ok(parsed[0], [ALLOWED]) is True
    assert lock.hash_ok(data, parsed[0]) is True
    resolved = lock.resolve(
        parsed,
        [{"name": "ACME_Utils", "version": "1.2.3"}],
    )
    assert resolved["acme-utils"]["version"] == "1.2.3"
    assert lock.diff(parsed, parsed) == {
        "missing": [],
        "extra": [],
        "changed": [],
    }
    assert lock.validate_policy(_policy()) == []

    batch = lock.lock_batch(
        [
            {
                "id": "app",
                "entries": parsed,
                "constraints": [{"name": "acme-utils", "version": "1.2.3"}],
            }
        ],
        _policy(),
    )
    assert batch["app"]["issues"] == []
    assert batch["app"]["resolved"]["acme-utils"]["version"] == "1.2.3"


def test_diff_reports_extra_same_named_mirror_package():
    expected = _entry(name="Acme_Utils", source=ALLOWED)
    extra = _entry(name="acme-utils", source=MIRROR)
    result = lock.diff([expected], [expected, extra])
    assert result["missing"] == []
    assert len(result["extra"]) == 1
    assert result["extra"][0]["source"] == MIRROR


def test_hash_mismatch_is_rejected():
    artifact = b"artifact-as-built"
    entry = _entry(data=b"artifact-as-locked")
    assert lock.hash_ok(artifact, entry) is False


def test_source_mismatch_is_rejected():
    entry = _entry(source="https://mirror.example/simple")
    assert lock.source_ok(entry, [ALLOWED]) is False


def test_batch_matches_individual_runs():
    policy = _policy()
    first = {
        "id": "one",
        "entries": [_entry(version="1.0.0", data=b"one")],
        "constraints": [{"name": "acme-utils", "version": "1.0.0"}],
    }
    second = {
        "id": "two",
        "entries": [
            _entry(name="other-pkg", version="9.9.9", data=b"other")
        ],
        "constraints": [{"name": "other-pkg", "version": "9.9.9"}],
    }

    combined = lock.lock_batch([first, second], policy)
    assert combined["one"] == lock.lock_batch([first], policy)["one"]
    assert combined["two"] == lock.lock_batch([second], policy)["two"]